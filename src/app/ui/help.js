function helpIcon(k) {
  return HELP[k] ? `<button type="button" class="help" data-help="${k}" aria-label="说明：${HELP[k].t}">?</button>` : '';
}

function renderHelpPage() {
  const toc = HELP_GROUPS.map(([g, ks]) => `<div class="help-toc-g"><b>${g}</b>${ks.map(k => `<a href="#help-${k}" onclick="event.preventDefault();showHelp('${k}')">${HELP[k].t}</a>`).join('')}</div>`).join('');
  const body = HELP_GROUPS.map(([g, ks]) => `<div class="sec-title">${g}</div>` + ks.map(k => `<div class="card help-sec" id="help-${k}"><div class="card-h"><span>${HELP[k].t}</span></div>${HELP[k].s ? `<p class="help-s">${HELP[k].s}</p>` : ''}<div class="help-b">${HELP[k].b}</div></div>`).join('')).join('');
  document.getElementById('helpToc').innerHTML = toc;
  document.getElementById('helpBody').innerHTML = body;
}

function showHelp(k) {
  go('help');
  const el = document.getElementById('help-' + k);
  if (!el) return;
  el.scrollIntoView({ block: 'start' });
  el.classList.remove('flash'); void el.offsetWidth; el.classList.add('flash');
}

// 悬停提示：一个浮层跟着「?」走（fixed 定位，不会被卡片 / 滚动区裁掉）
(function () {
  const tip = document.createElement('div');
  tip.className = 'help-tip'; tip.hidden = true;
  document.body.appendChild(tip);
  let cur = null;
  const hide = () => { tip.hidden = true; cur = null; };
  document.addEventListener('mouseover', e => {
    const h = e.target.closest('.help');
    if (!h) { if (cur) hide(); return; }
    if (h === cur) return;
    const k = h.dataset.help;
    if (!HELP[k]) return;
    cur = h;
    tip.innerHTML = `<b>${HELP[k].t}</b><span>${HELP[k].s}</span><small>点问号看详细说明</small>`;
    tip.hidden = false;
    const r = h.getBoundingClientRect(), tw = tip.offsetWidth, th = tip.offsetHeight;
    let x = Math.min(Math.max(8, r.left + r.width / 2 - tw / 2), innerWidth - tw - 8);
    let y = r.bottom + 8; if (y + th > innerHeight - 8) y = r.top - th - 8;
    tip.style.left = x + 'px'; tip.style.top = y + 'px';
  });
  document.addEventListener('click', e => {
    const h = e.target.closest('.help');
    if (!h) return;
    e.preventDefault(); e.stopPropagation();
    hide(); showHelp(h.dataset.help);
  }, true);
  document.addEventListener('scroll', hide, true);
})();

